#!/usr/bin/env python3
"""Regenerate the decision and open-question registers in 17-risks-and-open-questions.md.

Collects every "- **Dnn.m** text" and "- **Qnn.m** text" bullet (continuation lines indented by two spaces) from the
numbered documents of this directory and rewrites the block between the BEGIN/END markers in doc 17.
Run from anywhere:  python3 -I docs/trifecta/tools/gen_register.py
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(HERE, "17-risks-and-open-questions.md")
BEGIN, END = "<!-- BEGIN GENERATED REGISTER -->", "<!-- END GENERATED REGISTER -->"


def collect(kind):
    items = []
    for path in sorted(glob.glob(os.path.join(HERE, "[0-9][0-9]-*.md"))):
        name = os.path.basename(path)
        text = open(path, encoding="utf-8").read()
        if BEGIN in text and END in text:  # doc 17: parse only what lies outside the generated block
            pre, rest = text.split(BEGIN, 1)
            text = pre + rest.split(END, 1)[1]
        lines = text.split("\n")
        i = 0
        while i < len(lines):
            m = re.match(r"^- \*\*(%s\d\d\.\d+)\*\* (.*)$" % kind, lines[i])
            if m:
                text, j = m.group(2), i + 1
                while j < len(lines) and lines[j].startswith("  ") and not lines[j].lstrip().startswith("- "):
                    text += " " + lines[j].strip()
                    j += 1
                items.append((m.group(1), name, text.replace("|", "\\|")))
                i = j
                continue
            i += 1
    return items


def table(items, header):
    out = [f"| ID | {header} | Doc |", "|---|---|---|"]
    out += [f"| {i} | {t} | [{n[:2]}]({n}) |" for i, n, t in items]
    return "\n".join(out)


def main():
    d, q = collect("D"), collect("Q")
    block = "\n".join([
        BEGIN,
        f"_{len(d)} proposed decisions, {len(q)} open questions. Generated by `tools/gen_register.py`; do not edit by hand._",
        "",
        table(d, "Proposed decision"),
        "",
        "## 5. Open questions (generated)",
        "",
        table(q, "Open question"),
        END,
    ])
    src = open(TARGET, encoding="utf-8").read()
    if BEGIN in src and END in src:
        pre, rest = src.split(BEGIN, 1)
        post = rest.split(END, 1)[1]
        src = pre + block + post
    else:
        src = src.rstrip("\n") + "\n\n" + block + "\n"
    open(TARGET, "w", encoding="utf-8").write(src)
    print(f"register: {len(d)} decisions, {len(q)} questions -> {os.path.basename(TARGET)}")


if __name__ == "__main__":
    main()
