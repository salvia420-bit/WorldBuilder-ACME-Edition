    private DRW.DatCollection OpenUiCollectionRead(string? localDatPath) {
        var resolvedLocal = ResolveDatPathOrAlias(localDatPath, defaultAlias: "local");
        var resolvedPortal = ResolveDatPathOrAlias(null, defaultAlias: "portal");
        var opts = new DRW.Options.DatCollectionOptions {
            DatDirectory = Path.GetDirectoryName(resolvedLocal)!,
            AccessType = DRW.Options.DatAccessType.Read,
            LocalDatPath = resolvedLocal,
            PortalDatPath = resolvedPortal,
            HighResDatPath = resolvedPortal,
            CellDatPath = ResolveDatPathOrAlias(null, defaultAlias: "cell"),
        };
        return new DRW.DatCollection(opts);
    }
