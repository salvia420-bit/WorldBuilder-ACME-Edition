/// <summary>
/// UI workspace suite — the headless port of the two community desktop
/// tools studied 2026-07-02 (`AC_UI_Asset_Builder` v0.3, Rust/egui, and
/// `Asherons_Interface` v0.1, WPF/DatReaderWriter 2.1.6; sources under
/// /mnt/wbterminal2/asheron-ui-tools/ incl. ILSpy decompile in decomp/).
/// Five commands over the retail UI stack in the DATs:
///
///   - <c>ui-layout-list</c> — enumerate every LayoutDesc in the local
///     DAT with dims/element/image counts + resolved root names (the
///     Asherons-Interface layout dropdown, headless).
///
///   - <c>ui-layout-render</c> — compose a LayoutDesc to a PNG the way
///     the retail client would draw it: base-element inheritance chains
///     (BaseLayoutId/BaseElement), per-state media with the retail
///     fallback order (requested → Normal → default StateDesc), images
///     tiled at native size (the reference app's TileMode=Tile,
///     absolute-viewport behaviour), MediaDescAlpha masks multiplied
///     into the RGBA, MediaDescAnimation frame selection, and text drawn
///     with the RETAIL BITMAP FONTS (DBObjs.Font glyph atlas +
///     StringTable strings from client_local_English) honouring the
///     UICore_Text_* colour/justification/margin properties. Emits a
///     JSON render manifest alongside (what drew, what was skipped).
///
///   - <c>ui-element-edit</c> — the Asherons-Interface move/resize
///     workflow, headless: patch ElementDesc X/Y/Width/Height/ZLevel in
///     a LayoutDesc and write it back with TryWriteFile. Writes are
///     REFUSED against ~/ac_base_dats — point it at a copy.
///
///   - <c>ui-image-replace</c> — the Asset-Builder "Save to DAT" path:
///     PNG → RenderSurface (format preserved for R8G8B8/A8R8G8B8
///     originals, everything else re-encoded A8R8G8B8) written into a
///     portal-DAT copy. Batch via explicit pairs or a directory of
///     0x06XXXXXX.png files (the tools' baked/images convention).
///
///   - <c>ui-pack-export</c> — emit an AC_UI_Asset_Builder-compatible
///     <c>reference_pack.json</c> (BakedReferencePack version 1: panels
///     → flattened nodes with traversal indices, widget kinds, state
///     image sets; images[] usage cross-reference) + images/ PNGs, so
///     the community tool can open a workspace generated by us.
///
/// Property-ID constants and the justification/state fallback semantics
/// were lifted from the decompiled reference app (MainWindow.cs) and the
/// retail MasterPropertyId table it embeds; the pack schema field names
/// come from the Rust exe's serde struct strings (BakedReferencePack /
/// BakedImageEntry / BakedNodeUsage / BakedSkippedPanel).
/// </summary>
