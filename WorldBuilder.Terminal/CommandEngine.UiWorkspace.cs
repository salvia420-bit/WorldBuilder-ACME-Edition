    //  ui-image-replace
    // ─────────────────────────────────────────────────────────────────

    public sealed record UiImageReplaceSpec(uint Did, string PngPath);

    public UiImageReplaceResult UiImageReplace(
        string datPath, IReadOnlyList<UiImageReplaceSpec> replacements,
        bool dryRun, bool allowCreate) {
        if (replacements == null || replacements.Count == 0) {
            throw new ArgumentException(
                "No replacements resolved — pass a 'replacements' array or a 'fromDir' of 0x06XXXXXX.png files.");
        }
        var resolved = GuardWritableDatCopy(datPath);

        var records = new List<Dictionary<string, object?>>();
        int written = 0, failed = 0;

        using var portal = new DRW.PortalDatabase(resolved,
            dryRun ? DRW.Options.DatAccessType.Read : DRW.Options.DatAccessType.ReadWrite);

        foreach (var spec in replacements) {
            var rec = new Dictionary<string, object?> {
                ["didHex"] = $"0x{spec.Did:X8}",
                ["pngPath"] = spec.PngPath,
            };
            try {
                if (!File.Exists(spec.PngPath)) {
                    throw new FileNotFoundException($"png not found: {spec.PngPath}");
                }
                portal.TryGet<DRW.DBObjs.RenderSurface>(spec.Did, out var existing);
                if (existing == null && !allowCreate) {
                    throw new InvalidOperationException(
                        $"RenderSurface 0x{spec.Did:X8} not present in {Path.GetFileName(resolved)} " +
                        "(pass allowCreate=true to add a new record).");
                }

                using var img = Image.Load<Rgba32>(spec.PngPath);
                bool opaque = true;
                img.ProcessPixelRows(acc => {
                    for (int y = 0; y < acc.Height && opaque; y++) {
                        var row = acc.GetRowSpan(y);
                        for (int x = 0; x < row.Length; x++) {
                            if (row[x].A != 255) { opaque = false; break; }
                        }
                    }
                });

                // Format policy: keep R8G8B8 for opaque replacements of
                // R8G8B8 originals (byte layout BGR — the repo-wide trap
                // documented in RenderSurfaceExtensions); everything else
                // becomes A8R8G8B8 (BGRA). Palette/DXT/JPEG originals are
                // re-encoded — retail reads the per-record format field,
                // so mixed formats in one DAT are fine.
                var srcFormat = existing?.Format;
                bool asRgb = srcFormat == DRW.Enums.PixelFormat.PFID_R8G8B8 && opaque;
                byte[] data;
                if (asRgb) {
                    data = new byte[img.Width * img.Height * 3];
                    for (int y = 0; y < img.Height; y++)
                    for (int x = 0; x < img.Width; x++) {
                        var p = img[x, y];
                        int i = (y * img.Width + x) * 3;
                        data[i + 0] = p.B; data[i + 1] = p.G; data[i + 2] = p.R;
                    }
                } else {
                    data = new byte[img.Width * img.Height * 4];
                    for (int y = 0; y < img.Height; y++)
                    for (int x = 0; x < img.Width; x++) {
                        var p = img[x, y];
                        int i = (y * img.Width + x) * 4;
                        data[i + 0] = p.B; data[i + 1] = p.G; data[i + 2] = p.R; data[i + 3] = p.A;
                    }
                }

                var surface = new DRW.DBObjs.RenderSurface {
                    Id = spec.Did,
                    Width = img.Width,
                    Height = img.Height,
                    Format = asRgb ? DRW.Enums.PixelFormat.PFID_R8G8B8 : DRW.Enums.PixelFormat.PFID_A8R8G8B8,
                    DefaultPaletteId = existing?.DefaultPaletteId ?? 0,
                    SourceData = data,
                };

                rec["srcFormat"] = srcFormat?.ToString() ?? "(new)";
                rec["dstFormat"] = surface.Format.ToString();
                rec["width"] = img.Width;
                rec["height"] = img.Height;
                rec["bytes"] = data.Length;

                if (!dryRun) {
                    var result = portal.TryWriteFile(surface);
                    if (!result.Success) {
                        throw new InvalidOperationException($"TryWriteFile failed: {result.Error}");
                    }
                }
                rec["status"] = dryRun ? "DRY-RUN" : "WRITTEN";
                written++;
            } catch (Exception ex) {
                rec["status"] = "FAIL";
                rec["error"] = ex.Message;
                failed++;
            }
            records.Add(rec);
        }

        return new UiImageReplaceResult(
            DatPath: resolved, DryRun: dryRun,
            RequestedCount: replacements.Count,
            WrittenCount: dryRun ? 0 : written,
            FailCount: failed,
            Records: records);
    }

    // ─────────────────────────────────────────────────────────────────
    //  ui-pack-export
    // ─────────────────────────────────────────────────────────────────

    public UiPackExportResult UiPackExport(
        string outDir, IReadOnlyList<uint>? layoutIds, string? datPath, bool includeImages) {
        if (string.IsNullOrWhiteSpace(outDir)) {
            throw new ArgumentException("outDir is required.");
        }
        Directory.CreateDirectory(outDir);

        using var collection = OpenUiCollectionRead(datPath);

        var ids = (layoutIds != null && layoutIds.Count > 0)
            ? layoutIds.Distinct().OrderBy(i => i).ToList()
            : collection.Local.GetAllIdsOfType<DRW.DBObjs.LayoutDesc>().OrderBy(i => i).ToList();

        var panels = new List<Dictionary<string, object?>>();
        // image key → usage aggregation
        var imageUsage = new Dictionary<(uint ImageId, uint AlphaId), (SortedSet<string> Panels, List<Dictionary<string, object?>> Nodes)>();
        int nodeTotal = 0;
        var skipped = new List<Dictionary<string, object?>>();

        foreach (var layoutId in ids) {
            if (!collection.TryGet<DRW.DBObjs.LayoutDesc>(layoutId, out var layout) || layout == null) {
                skipped.Add(new Dictionary<string, object?> {
                    ["layout_id"] = layoutId, ["reason"] = "LayoutDesc not found",
                });
                continue;
            }
            var firstRoot = layout.Elements.Values.OrderBy(e => e.ReadOrder).FirstOrDefault();
            var rootName = firstRoot != null ? TryResolveUiElementIdName(firstRoot.ElementId) : null;
            var slug = MakePanelSlug(rootName, layoutId);

            var nodes = new List<Dictionary<string, object?>>();
            int traversal = 0;

            void WalkNode(DRW.Types.ElementDesc el, int? parentTraversal, int parentAbsX, int parentAbsY) {
                int myIndex = traversal++;
                int absX = parentAbsX + (int)el.X;
                int absY = parentAbsY + (int)el.Y;

                var (defaultImage, states) = ExtractStateImages(el);
                var kind = ClassifyWidgetKind(el, defaultImage != null || states.Count > 0);

                nodes.Add(new Dictionary<string, object?> {
                    ["traversal_index"] = myIndex,
                    ["element_id"] = el.ElementId,
                    ["layout_id"] = layoutId,
                    ["parent_layout_id"] = parentTraversal.HasValue ? layoutId : (uint?)null,
                    ["parent_traversal_index"] = parentTraversal,
                    ["base_layout_id"] = el.BaseLayoutId,
                    ["rect"] = new Dictionary<string, object?> {
                        ["x"] = (float)absX, ["y"] = (float)absY,
                        ["width"] = (float)el.Width, ["height"] = (float)el.Height,
                    },
                    ["widget_kind"] = kind,
                    ["state_set"] = new Dictionary<string, object?> {
                        ["default_image"] = defaultImage,
                        ["states"] = states,
                    },
                });

                void Record(Dictionary<string, object?>? imageKey, uint? stateId) {
                    if (imageKey == null) return;
                    var key = ((uint)(imageKey["image_id"] ?? 0u),
                               (uint)(imageKey["alpha_image_id"] ?? 0u));
                    if (!imageUsage.TryGetValue(key, out var agg)) {
                        agg = (new SortedSet<string>(StringComparer.Ordinal), new List<Dictionary<string, object?>>());
                        imageUsage[key] = agg;
                    }
                    agg.Panels.Add(slug);
                    agg.Nodes.Add(new Dictionary<string, object?> {
                        ["panel_slug"] = slug,
                        ["traversal_index"] = myIndex,
                        ["element_id"] = el.ElementId,
                        ["state_id"] = stateId,
                    });
                }
                Record(defaultImage, null);
                foreach (var s in states) {
                    Record(s["image"] as Dictionary<string, object?>, (uint?)(s["state_id"] as uint?));
                }

                if (el.Children != null) {
                    foreach (var c in el.Children.Values.OrderBy(e => e.ReadOrder).ThenBy(e => e.ElementId)) {
                        WalkNode(c, myIndex, absX, absY);
                    }
                }
            }

            foreach (var root in layout.Elements.Values.OrderBy(e => e.ReadOrder).ThenBy(e => e.ElementId)) {
                WalkNode(root, null, 0, 0);
            }
            nodeTotal += nodes.Count;

            panels.Add(new Dictionary<string, object?> {
                ["id"] = firstRoot?.ElementId ?? layoutId,
                ["slug"] = slug,
                ["title"] = MakePanelTitle(rootName, layoutId),
                ["bucket"] = "Exported",
                ["parent_slug"] = null,
                ["width"] = layout.Width,
                ["height"] = layout.Height,
                ["nodes"] = nodes,
            });
        }

        // images[] — decode dims + optionally extract PNGs via the
        // existing extractor (which also writes its INDEX.json).
        string? imagesDir = null;
        int pngPass = 0, pngFail = 0;
        var allDids = imageUsage.Keys
            .SelectMany(k => new[] { k.ImageId, k.AlphaId })
            .Where(d => d != 0).Distinct().OrderBy(d => d).ToList();
        var dimsByDid = new Dictionary<uint, (int W, int H)>();
        if (includeImages && allDids.Count > 0) {
            imagesDir = Path.Combine(outDir, "images");
            var extract = ChoriziteExtractUiTextures(allDids, imagesDir, datPath: null);
            pngPass = extract.PngCount;
            pngFail = extract.FailCount;
            foreach (var r in extract.Records) {
                if (r.Status == "PASS") dimsByDid[r.Did] = (r.Width, r.Height);
            }
        }

        var images = new List<Dictionary<string, object?>>();
        foreach (var kvp in imageUsage.OrderBy(k => k.Key.ImageId).ThenBy(k => k.Key.AlphaId)) {
            dimsByDid.TryGetValue(kvp.Key.ImageId, out var dims);
            images.Add(new Dictionary<string, object?> {
                ["key"] = new Dictionary<string, object?> {
                    ["image_id"] = kvp.Key.ImageId,
                    ["alpha_image_id"] = kvp.Key.AlphaId == 0 ? null : (uint?)kvp.Key.AlphaId,
                },
                ["relative_path"] = $"images/0x{kvp.Key.ImageId:X8}.png",
                ["width"] = dims.W,
                ["height"] = dims.H,
                ["used_by_panels"] = kvp.Value.Panels.ToList(),
                ["used_by_nodes"] = kvp.Value.Nodes,
            });
        }

        var pack = new Dictionary<string, object?> {
            ["version"] = 1,
            ["panels"] = panels,
            ["images"] = images,
            ["skipped_panels"] = skipped,
        };
        var packJsonPath = Path.Combine(outDir, "reference_pack.json");
        File.WriteAllText(packJsonPath, JsonSerializer.Serialize(pack,
            new JsonSerializerOptions { WriteIndented = true }));

        return new UiPackExportResult(
            OutDir: Path.GetFullPath(outDir),
            PackJsonPath: Path.GetFullPath(packJsonPath),
            PanelCount: panels.Count,
            NodeCount: nodeTotal,
            ImageCount: images.Count,
            PngPass: pngPass,
            PngFail: pngFail,
            ImagesDir: imagesDir != null ? Path.GetFullPath(imagesDir) : null);
    }

    /// <summary>default_image + per-state image keys for one element —
    /// first Image media of a StateDesc, paired with an Alpha media in
    /// the same state (the pack's {image_id, alpha_image_id} shape).</summary>
    private static (Dictionary<string, object?>? DefaultImage, List<Dictionary<string, object?>> States)
        ExtractStateImages(DRW.Types.ElementDesc el) {

        static Dictionary<string, object?>? FirstImageKey(DRW.Types.StateDesc? s) {
            if (s?.Media == null) return null;
            uint image = 0, alpha = 0;
            foreach (var m in s.Media) {
                if (image == 0 && m is DRW.Types.MediaDescImage i) image = i.File;
                if (alpha == 0 && m is DRW.Types.MediaDescAlpha a) alpha = a.File;
            }
            if (image == 0) return null;
            return new Dictionary<string, object?> {
                ["image_id"] = image,
                ["alpha_image_id"] = alpha == 0 ? null : (uint?)alpha,
            };
        }

        var def = FirstImageKey(el.StateDesc);
        var states = new List<Dictionary<string, object?>>();
        if (el.States != null) {
            foreach (var kvp in el.States.OrderBy(k => (uint)k.Key)) {
                var key = FirstImageKey(kvp.Value);
                if (key == null) continue;
                states.Add(new Dictionary<string, object?> {
                    ["state_id"] = (uint)kvp.Key,
                    ["image"] = key,
                });
            }
        }
        return (def, states);
    }

    /// <summary>Best-effort widget classification mirroring the Rust
    /// pack's vocabulary {Group, Sprite, Button, Scrollbar, Slider} from
    /// the retail element Type (ACElementType: Button=1, Dragbar=2,
    /// Meter=7, Scrollbar=11 per the reference app's enum).</summary>
    private static string ClassifyWidgetKind(DRW.Types.ElementDesc el, bool hasImage) {
        return el.Type switch {
            1 => "Button",
            11 => "Scrollbar",
            2 or 7 => "Slider",
            _ => hasImage ? "Sprite" : "Group",
        };
    }

    private static string MakePanelSlug(string? rootName, uint layoutId) {
        if (!string.IsNullOrEmpty(rootName)) {
            var s = rootName;
            if (s.StartsWith("Root", StringComparison.Ordinal)) s = s.Substring(4);
            if (s.EndsWith("_Field", StringComparison.Ordinal)) s = s.Substring(0, s.Length - 6);
            s = string.Concat(s.Select((c, i) =>
                char.IsUpper(c) && i > 0 && !char.IsUpper(s[i - 1]) ? "_" + char.ToLowerInvariant(c) : char.ToLowerInvariant(c).ToString()));
            s = s.Replace("__", "_").Trim('_');
            if (s.Length > 0) return s;
        }
        return $"layout_{layoutId:x8}";
    }

    private static string MakePanelTitle(string? rootName, uint layoutId) {
        var slug = MakePanelSlug(rootName, layoutId);
        return string.Join(" ", slug.Split('_', StringSplitOptions.RemoveEmptyEntries)
            .Select(w => w.Length > 0 ? char.ToUpperInvariant(w[0]) + w.Substring(1) : w));
    }

