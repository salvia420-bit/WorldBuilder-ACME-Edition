    public sealed record UiElementEditSpec(
        uint ElementId, uint? X, uint? Y, uint? Width, uint? Height, uint? ZLevel);

    public UiElementEditResult UiElementEdit(
        string datPath, uint layoutId, IReadOnlyList<UiElementEditSpec> edits, bool dryRun) {
        if (edits == null || edits.Count == 0) {
            throw new ArgumentException("edits array is required and must be non-empty.");
        }
        var resolved = Path.GetFullPath(GuardWritableDatCopy(datPath));

        // Read through a full collection so BaseProperty.UnpackGeneric can
        // resolve the portal MasterProperty (same wiring as the dump
        // command); the LOCAL side reads from the caller's copy.
        DRW.DBObjs.LayoutDesc layout;
        {
            var portal = ResolveDatPathOrAlias(null, defaultAlias: "portal");
            var opts = new DRW.Options.DatCollectionOptions {
                DatDirectory = Path.GetDirectoryName(resolved)!,
                AccessType = DRW.Options.DatAccessType.Read,
                LocalDatPath = resolved,
                PortalDatPath = portal,
                HighResDatPath = portal,
                CellDatPath = ResolveDatPathOrAlias(null, defaultAlias: "cell"),
            };
            using var collection = new DRW.DatCollection(opts);
            if (!collection.TryGet<DRW.DBObjs.LayoutDesc>(layoutId, out var l) || l == null) {
                throw new InvalidOperationException($"LayoutDesc 0x{layoutId:X8} not found in {resolved}.");
            }
            layout = l;
        }

        var reports = new List<Dictionary<string, object?>>();
        int applied = 0;
        foreach (var edit in edits) {
            var el = FindElementDeep(layout, edit.ElementId);
            var rep = new Dictionary<string, object?> {
                ["elementIdHex"] = $"0x{edit.ElementId:X8}",
                ["found"] = el != null,
            };
            if (el != null) {
                rep["before"] = new { x = el.X, y = el.Y, width = el.Width, height = el.Height, zLevel = el.ZLevel };
                if (edit.X.HasValue) el.X = edit.X.Value;
                if (edit.Y.HasValue) el.Y = edit.Y.Value;
                if (edit.Width.HasValue) el.Width = edit.Width.Value;
                if (edit.Height.HasValue) el.Height = edit.Height.Value;
                if (edit.ZLevel.HasValue) el.ZLevel = edit.ZLevel.Value;
                rep["after"] = new { x = el.X, y = el.Y, width = el.Width, height = el.Height, zLevel = el.ZLevel };
                applied++;
            }
            reports.Add(rep);
        }

        bool written = false;
        if (!dryRun && applied > 0) {
            // Write through a dedicated ReadWrite handle. Pack() has no
            // MasterProperty dependency (verified against 2.1.2 — only
            // UnpackGeneric reaches the collection), so a bare
            // LocalDatabase suffices.
            using var rw = new DRW.LocalDatabase(resolved, DRW.Options.DatAccessType.ReadWrite);
            var result = rw.TryWriteFile(layout);
            if (!result.Success) {
                throw new InvalidOperationException($"TryWriteFile failed: {result.Error}");
            }
            written = true;
        }

        return new UiElementEditResult(
            DatPath: resolved,
            LayoutIdHex: $"0x{layoutId:X8}",
            DryRun: dryRun,
            Written: written,
            Edits: reports);
    }

    private static DRW.Types.ElementDesc? FindElementDeep(DRW.DBObjs.LayoutDesc layout, uint elementId) {
        DRW.Types.ElementDesc? Find(DRW.Types.ElementDesc el) {
            if (el.ElementId == elementId) return el;
            if (el.Children != null) {
                foreach (var c in el.Children.Values) {
                    var hit = Find(c);
                    if (hit != null) return hit;
                }
            }
            return null;
        }
        foreach (var root in layout.Elements.Values) {
            var hit = Find(root);
            if (hit != null) return hit;
        }
        return null;
    }

    /// <summary>Writable-copy guard shared by the two write commands:
    /// the path must exist and must NOT live under ~/ac_base_dats (the
    /// pristine bake inputs are never written — point the command at a
    /// copy).</summary>
    private static string GuardWritableDatCopy(string datPath) {
        if (string.IsNullOrWhiteSpace(datPath)) {
            throw new ArgumentException(
                "datPath is required for write commands and must point at a DAT COPY (never ~/ac_base_dats).");
        }
        var full = Path.GetFullPath(datPath.Trim());
        if (!File.Exists(full)) {
            throw new FileNotFoundException($"datPath not found: {full}");
        }
        var baseDats = Path.GetFullPath(Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), "ac_base_dats"));
        if (full.StartsWith(baseDats + Path.DirectorySeparatorChar, StringComparison.Ordinal)
            || full.Equals(baseDats, StringComparison.Ordinal)) {
            throw new InvalidOperationException(
                $"Refusing to write into ~/ac_base_dats ({full}) — copy the DAT elsewhere first (base DATs stay pristine).");
        }
        return full;
    }

