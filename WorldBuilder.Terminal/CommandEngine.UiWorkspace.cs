    public UiLayoutListResult UiLayoutList(string? datPath) {
        using var collection = OpenUiCollectionRead(datPath);
        var localPath = ResolveDatPathOrAlias(datPath, defaultAlias: "local");

        var entries = new List<UiLayoutListEntry>();
        foreach (var id in collection.Local.GetAllIdsOfType<DRW.DBObjs.LayoutDesc>().OrderBy(i => i)) {
            if (!collection.TryGet<DRW.DBObjs.LayoutDesc>(id, out var layout) || layout == null) continue;

            int total = 0;
            var dids = new SortedSet<uint>();
            void Walk(DRW.Types.ElementDesc el) {
                total++;
                CollectStateDids(el.StateDesc, dids);
                if (el.States != null) {
                    foreach (var s in el.States.Values) CollectStateDids(s, dids);
                }
                if (el.Children != null) {
                    foreach (var c in el.Children.Values) Walk(c);
                }
            }
            foreach (var root in layout.Elements.Values) Walk(root);

            var firstRoot = layout.Elements.Values
                .OrderBy(e => e.ReadOrder).FirstOrDefault();
            entries.Add(new UiLayoutListEntry(
                LayoutIdHex: $"0x{id:X8}",
                LayoutId: id,
                Width: layout.Width,
                Height: layout.Height,
                RootCount: layout.Elements.Count,
                ElementCount: total,
                ImageDidCount: dids.Count,
                RootElementIdName: firstRoot != null
                    ? TryResolveUiElementIdName(firstRoot.ElementId) : null));
        }
        return new UiLayoutListResult(localPath, entries.Count, entries);
    }

    /// <summary>Collect image DIDs referenced by one StateDesc — both the
    /// media list and any DID-shaped property value (same window the
    /// dump command uses).</summary>
    private static void CollectStateDids(DRW.Types.StateDesc? state, SortedSet<uint> sink) {
        if (state == null) return;
        if (state.Media != null) {
            foreach (var m in state.Media) {
                foreach (var f in m.GetType().GetFields(
                    System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance)) {
                    CollectImageDidsFromValue(f.GetValue(m), sink);
                }
            }
        }
        if (state.Properties != null) {
            foreach (var kvp in state.Properties) {
                var valueField = kvp.Value.GetType().GetField("Value");
                var maybe = ExtractMaybeUint(valueField?.GetValue(kvp.Value));
                if (maybe.HasValue && IsImageDid(maybe.Value)) sink.Add(maybe.Value);
            }
        }
    }

